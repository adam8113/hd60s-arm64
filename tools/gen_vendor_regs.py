#!/usr/bin/env python3
"""build src/vendor_regs.h from a decoded good-run trace.

Every register read in the capture carries the value the vendor driver's card
actually held. Collecting the most common value per register gives a reference
state to diff ours against (./start vdiff).

usage: gen_vendor_regs.py vendor_regs.txt
  where vendor_regs.txt is the tab-separated dump produced on the capture host.
"""
import sys
src = sys.argv[1] if len(sys.argv) > 1 else 'data/vendor_regs.txt'
rows = []
for line in open(src):
    p = line.rstrip('\n').split('\t')
    if len(p) != 5 or p[0] not in ('vid', 'mcu'):
        continue
    rows.append((0 if p[0] == 'vid' else 1, int(p[1]), int(p[2], 16),
                 int(p[3], 16), int(p[4])))
with open('src/vendor_regs.h', 'w') as f:
    f.write("// Generated by tools/gen_vendor_regs.py. Do not hand-edit.\n"
            "// The value each register held in the vendor driver's working session,\n"
            "// taken as the most common value across every read of it in the capture.\n"
            "#pragma once\n#include <cstdint>\n\n"
            "struct VendorReg { uint8_t kind, page, reg, val; uint16_t samples; };\n\n"
            "static const VendorReg kVendorRegs[] = {\n")
    for k, pg, r, v, n in rows:
        f.write(f"    {{ {k}, {pg}, 0x{r:02x}, 0x{v:02x}, {min(n, 65535)} }},\n")
    f.write(f"}};\nstatic const int kVendorRegsLen = {len(rows)};\n")
print(f"{len(rows)} registers -> src/vendor_regs.h", file=sys.stderr)
