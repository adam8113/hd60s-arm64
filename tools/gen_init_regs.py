#!/usr/bin/env python3
"""regenerate src/init_regs.h from a decode_trace.py --seq window.

Input format is the --seq one: dir|bReq|wValue|wIndex|len|data. The earlier
version of this script read the older text dumps, which had no wIndex column,
and that loss mattered: the FX3 direct port at wValue 0x004C carries its
register there, and the 0xC6 init command uses wIndex 0x0100.

  kind 0  video front end (I2C 0x9c) register write, page tracked
  kind 1  MCU command, variable length payload
  kind 2  HDMI transmitter (I2C 0x98) register write
  kind 3  bare control request; aux = bRequest, wValue and wIndex carried
  kind 4  FX3 direct port write (wValue 0x004C); aux = register from wIndex

usage: gen_init_regs.py data/cold-init.txt [--edid]
"""
import sys

src = sys.argv[1] if len(sys.argv) > 1 else 'data/cold-init.txt'
keep_edid = '--edid' in sys.argv
page, ops = None, []
for line in open(src):
    f = line.rstrip('\n').split('|')
    if len(f) < 6 or f[0] != 'OUT':
        continue
    breq, wv, wi, data = f[1], int(f[2], 16), int(f[3], 16), f[5]
    b = [int(x, 16) for x in data.split()] if data.strip() else []
    if breq == '0xc0' and wv == 0x509c and len(b) == 2:
        if b[0] == 0x00:
            page = b[1]
        else:
            ops.append((0, page, 0, b))
    elif breq == '0xc0' and wv == 0x5066 and b:
        if b[0] in (0x9b, 0x9d):            # reads carry no configuration
            continue
        if b[0] in (0xd4, 0xd5) and not keep_edid:
            continue
        ops.append((1, 0, 0, b))
    elif breq == '0xc0' and wv == 0x5098 and len(b) == 2:
        ops.append((2, 0, 0, b))
    elif breq == '0xc0' and wv == 0x004c and b:
        ops.append((4, wi & 0xff, 0, b))
    elif breq in ('0xc1', '0xc2', '0xc6', '0xc7'):
        ops.append((3, int(breq, 16), wi, [wv & 0xff, (wv >> 8) & 0xff]))

maxlen = max((len(o[3]) for o in ops), default=2)
with open('src/init_regs.h', 'w') as f:
    f.write("// Generated by tools/gen_init_regs.py from a genuine cold-plug trace.\n"
            "// kind 0 video front end (0x9c) on `aux` page; 1 MCU command;\n"
            "// 2 HDMI tx (0x98); 3 bare control, aux = bRequest, data = wValue lo/hi,\n"
            "// windex carried separately; 4 FX3 direct port, aux = register.\n"
            "#pragma once\n#include <cstdint>\n\n"
            f"#define INITREG_MAX {maxlen}\n\n"
            "struct InitReg { uint8_t kind, aux, len; uint16_t windex; uint8_t data[INITREG_MAX]; };\n\n"
            "static const InitReg kColdInit[] = {\n")
    for k, aux, wi, b in ops:
        pad = b + [0] * (maxlen - len(b))
        f.write(f"    {{ {k}, 0x{aux:02x}, {len(b)}, 0x{wi:04x}, {{ "
                + ', '.join(f"0x{x:02x}" for x in pad) + " } },\n")
    f.write(f"}};\nstatic const int kColdInitLen = {len(ops)};\n")

from collections import Counter
c = Counter(o[0] for o in ops)
print(f"{len(ops)} ops -> src/init_regs.h  "
      f"(video {c[0]}, MCU {c[1]}, hdmi-tx {c[2]}, control {c[3]}, port {c[4]})",
      file=sys.stderr)
